-- ============================================================================
-- PNK Carta Digital — Esquema PostgreSQL (puerto fiel del esquema MySQL v2)
-- Tercera evaluación: Node.js + Express + PostgreSQL + MVC
--
-- Notas de migración MySQL -> PostgreSQL:
--   * int AUTO_INCREMENT      -> GENERATED ... AS IDENTITY
--   * bit(1) b'1'/b'0'        -> boolean
--   * datetime                -> timestamptz (se guarda en UTC)
--   * utf8mb4                 -> la base se crea con ENCODING 'UTF8'
--   * Se conservan los nombres de tabla originales (incl. "restautantes")
--     para no romper relaciones ni los datos sembrados.
--   * Se añaden claves foráneas e índices que el esquema original documentaba
--     en comentarios pero no imponía.
-- Seguridad: no hay cuentas por defecto (OWASP ASVS v5.0.0-6.3.2).
-- ============================================================================

-- Las consultas de la app usan el rol de aplicación de menor privilegio.
-- El esquema se crea con el rol administrador del contenedor (POSTGRES_USER).

BEGIN;

-- ---------------------------------------------------------------------------
-- direcciones
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS direcciones (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  calle        varchar(100) NOT NULL,
  numero       varchar(15)  NOT NULL,
  comuna       varchar(100) NOT NULL,
  region       varchar(100),
  creado       timestamptz DEFAULT now(),
  actualizado  timestamptz,
  eliminado    timestamptz
);

-- ---------------------------------------------------------------------------
-- restautantes  (se conserva el nombre original del esquema)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS restautantes (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rut            varchar(11)  NOT NULL,
  nombre         varchar(200) NOT NULL,
  fono           varchar(45)  NOT NULL,
  mapa           varchar(200),
  foto           varchar(200),
  email          varchar(100),
  creado         timestamptz DEFAULT now(),
  actualizado    timestamptz,
  eliminado      timestamptz,
  direcciones_id integer NOT NULL REFERENCES direcciones(id)
);
CREATE INDEX IF NOT EXISTS idx_resto_direccion ON restautantes(direcciones_id);

-- ---------------------------------------------------------------------------
-- cartas
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS cartas (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          varchar(45),
  orden           integer,
  visible         boolean DEFAULT true,
  foto            varchar(200),
  creada          timestamptz DEFAULT now(),
  actualizada     timestamptz,
  eliminada       timestamptz,
  restautantes_id integer NOT NULL REFERENCES restautantes(id)
);
CREATE INDEX IF NOT EXISTS idx_cartas_resto ON cartas(restautantes_id);

-- ---------------------------------------------------------------------------
-- categorias
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS categorias (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      varchar(100) NOT NULL,
  visible     boolean DEFAULT false,
  foto        varchar(200),
  orden       integer,
  creado      timestamptz DEFAULT now(),
  actualizado timestamptz,
  eliminado   timestamptz,
  cartas_id   integer NOT NULL REFERENCES cartas(id)
);
CREATE INDEX IF NOT EXISTS idx_categorias_carta ON categorias(cartas_id);

-- ---------------------------------------------------------------------------
-- items  (platos / bebidas / postres)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS items (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        varchar(100) NOT NULL,
  descripcion   varchar(300),
  tiempo        varchar(100),
  observaciones varchar(300),
  precio        integer,
  visible       boolean DEFAULT false,
  destacado     boolean DEFAULT false,
  puntuacion    integer DEFAULT 0 CHECK (puntuacion BETWEEN 0 AND 5),
  foto          varchar(200),
  orden         integer,
  creado        timestamptz DEFAULT now(),
  actualizado   timestamptz,
  eliminado     timestamptz,
  categorias_id integer NOT NULL REFERENCES categorias(id)
);
CREATE INDEX IF NOT EXISTS idx_items_categoria ON items(categorias_id);

-- ---------------------------------------------------------------------------
-- usuarios  (sin cuentas por defecto; hash bcrypt, MFA TOTP opcional)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS usuarios (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      varchar(255),
  email       varchar(255) NOT NULL,
  password    varchar(255) NOT NULL,            -- hash bcrypt, nunca texto plano
  estado      varchar(255) DEFAULT '1',         -- '1' activo; otro = bloqueado
  totp_secret varchar(64),                      -- base32 MFA/TOTP; NULL = sin 2FA
  CONSTRAINT uq_usuarios_email UNIQUE (email)
);

-- ---------------------------------------------------------------------------
-- comentarios  (autor autenticado -> control de propiedad anti-IDOR)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS comentarios (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario        varchar(255),
  usuario_id     integer REFERENCES usuarios(id),
  comentario     varchar(1000),
  id_restaurante integer REFERENCES restautantes(id),
  creado         timestamptz          -- UTC
);
CREATE INDEX IF NOT EXISTS idx_com_resto   ON comentarios(id_restaurante);
CREATE INDEX IF NOT EXISTS idx_com_usuario ON comentarios(usuario_id);

-- ---------------------------------------------------------------------------
-- login_intentos  (anti fuerza bruta, ASVS v5.0.0-6.3.1)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS login_intentos (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email_hash char(16) NOT NULL,   -- HMAC seudonimizado del correo, no el correo
  ip         varchar(45) NOT NULL,
  fecha      timestamptz NOT NULL -- UTC
);
CREATE INDEX IF NOT EXISTS idx_li_email_fecha ON login_intentos(email_hash, fecha);
CREATE INDEX IF NOT EXISTS idx_li_ip_fecha    ON login_intentos(ip, fecha);

COMMIT;
